export function getFoodsByCategory(category: FoodCategory): FoodDB[] {
  return FOODS.filter((f) => f.category === category);
}

export function getVegetarianFoods(): FoodDB[] {
  return FOODS.filter((f) => f.vegetariano);
}

export function getVeganFoods(): FoodDB[] {
  return FOODS.filter((f) => f.vegano);
}

export function getFoodsByMeal(meal: MealTime): FoodDB[] {
  return FOODS.filter((f) => f.meals.includes(meal));
}

export function calculateFoodCalories(food: FoodDB, grams: number): number {
  return Math.round((food.caloriasPor100g * grams) / 100);
}

export function calculateFoodProtein(food: FoodDB, grams: number): number {
  return Math.round((food.proteinaPor100g * grams) / 100 * 10) / 10;
}
